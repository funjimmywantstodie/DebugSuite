local function tokenTexts(source, kind)
    local values, reconstructed = {}, {}
    for _, token in SyntaxHighlight.Tokenize(source) do
        assert(source:sub(token.start, token.finish) == token.text)
        table.insert(reconstructed, token.text)
        if token.kind == kind then table.insert(values, token.text) end
    end
    assert(table.concat(reconstructed) == source)
    return table.concat(values, "|")
end
local sample = "local x = 1..2 -- print('ignored')\r\nreturn [==[<font> & text]==]"
assert(tokenTexts(sample, "keyword") == "local|return")
assert(tokenTexts(sample, "comment") == "-- print('ignored')")
assert(tokenTexts(sample, "number") == "1|2")
assert(tokenTexts(sample, "string") == "[==[<font> & text]==]")
assert(tokenTexts("0xff 0b10_01 .5 1.25e-3 1_000", "number") == "0xff|0b10_01|.5|1.25e-3|1_000")
assert(tokenTexts("0x1.fp+2 1...2", "number") == "0x1.fp+2|1|2")
assert(tokenTexts("--[=[comment\nlocal print]=]\nprint('hello')", "builtin") == "print")
assert(tokenTexts("'a\\'b' \"-- hi\" `hello {name}`", "string") == "'a\\'b'|\"-- hi\"|`hello {name}`")
assert(tokenTexts("--[==[unfinished", "comment") == "--[==[unfinished")
assert(tokenTexts("[=[unfinished", "string") == "[=[unfinished")
assert(tokenTexts("'unfinished\nreturn true", "keyword") == "return|true")
assert(SyntaxHighlight.Highlight("") == "")
assert(SyntaxHighlight.Escape("<&>\"'") == "&lt;&amp;&gt;&quot;&apos;")
assert(SyntaxHighlight.Highlight("local", { keyword = "#123456" }) == '<font color="#123456">local</font>')
assert(not pcall(function() SyntaxHighlight.Highlight("local", { keyword = '\" injected' }) end))
assert(not pcall(function() SyntaxHighlight.ValidateSyntax("python") end))
assert(SyntaxHighlight.Highlight("\"<font>\""):find("&lt;font&gt;", 1, true))
